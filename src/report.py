"""Auto-generate reports/results_summary.md from outputs/ (no hand-typed numbers)."""
from __future__ import annotations

import json

import pandas as pd

from . import config as C
from .audit import _md


def fy(y: int) -> str:
    return f"FY{y-1}-{str(y)[-2:]}"


def main() -> None:
    nat = pd.read_csv(C.DERIVED / "national_generation_fy.csv")
    mix = pd.read_csv(C.DERIVED / "national_mix_fy.csv")
    st = pd.read_csv(C.OUTPUTS / "national_forecast_statistical.csv")
    sc = pd.read_csv(C.OUTPUTS / "national_scenarios.csv")
    rs = pd.read_csv(C.OUTPUTS / "regional_summary.csv")
    al = pd.read_csv(C.OUTPUTS / "regional_allocation.csv")
    bt1 = pd.read_csv(C.OUTPUTS / "backtest_cea_fy_summary.csv")
    bt2 = pd.read_csv(C.OUTPUTS / "backtest_ember_cy_summary.csv")
    btg = pd.read_csv(C.OUTPUTS / "backtest_gdp_elasticity_vs_rw.csv")
    nep = pd.read_csv(C.OUTPUTS / "crosscheck_nep_requirement.csv")
    chk = pd.read_csv(C.OUTPUTS / "validation_checks.csv")
    cons = pd.read_csv(C.OUTPUTS / "allocation_conservation_checks.csv")
    fm = json.loads((C.OUTPUTS / "forecast_meta.json").read_text())
    sm = json.loads((C.OUTPUTS / "scenario_meta.json").read_text())
    am = json.loads((C.OUTPUTS / "allocation_meta.json").read_text())
    H = C.HEADLINE_FY_END
    base = nat.set_index("fy_end_year").loc[C.BASE_FY_END]

    L = ["# Results summary (auto-generated by `src/report.py` from `outputs/`)\n",
         "All values in TWh (= BU) of electricity **generated**. Observed = CEA/MoP; projections = model output.\n",
         "## 1. Observed baseline\n",
         f"* {fy(C.BASE_FY_END)} total generation (CEA, utilities incl. RE and Bhutan import): **{base.total_twh:,.1f} TWh**; "
         f"Bhutan import {base.bhutan_import_twh:,.2f} TWh; domestic {base.domestic_twh:,.1f} TWh.",
         f"* Growth {fy(C.BASE_FY_END)} vs {fy(C.BASE_FY_END-1)}: "
         f"{100*(base.total_twh/nat.set_index('fy_end_year').loc[C.BASE_FY_END-1,'total_twh']-1):.2f}% "
         f"(FY2009-10..{fy(C.BASE_FY_END)} CAGR "
         f"{100*((base.total_twh/nat.total_twh.iloc[0])**(1/(len(nat)-1))-1):.2f}%).\n"]
    m = mix[mix.fy_end_year == C.BASE_FY_END][["source", "twh", "share", "value_type"]].copy()
    m["share"] = (100 * m["share"]).round(2)
    L += [f"{fy(C.BASE_FY_END)} domestic mix:\n", _md(m), "\n"]

    L += ["## 2. Statistical models - rolling-origin backtests\n",
          f"Selected interval model: **{fm['selected_model']}** (rule: {fm['selection_rule']}).\n",
          "CEA FY total (expanding window from 7 obs; horizons 1-5):\n", _md(bt1.round(2)),
          "\n\nEmber calendar-year total (expanding window from 10 obs; horizons 1-5):\n", _md(bt2.round(2)),
          "\n\nGDP-elasticity engine vs RW-drift on identical origin/target pairs (elasticity CONDITIONAL on realised GDP):\n",
          _md(btg.round(2)), "\n"]
    s = st[st.fy_end_year.isin([2030, 2035, 2040, H])].copy()
    L += ["Statistical forecasts (CEA-total basis incl. Bhutan imports; point = median). **Intervals are model-based; "
          "beyond 5-year horizons they are illustrative long-horizon extrapolations, NOT empirically calibrated** "
          "(CEA backtest 95% coverage at horizons 1-5: "
          f"{bt1.set_index('model').loc['rw_drift','coverage95_pct']:.1f}%):\n",
          _md(s.drop(columns=["value_type", "interval_label"]).round(0)), "\n"]

    e = sm["elasticity"]
    L += ["## 3. Scenario projections\n",
          f"Historical generation-GDP elasticity (Ember generation vs Maddison real GDP, {e['window_years'][0]}-{e['window_years'][1]} "
          f"cumulative log ratio): **{e['eps0_trailing_ratio']:.3f}**; OLS slope with intercept {e['ols_slope']:.3f} "
          f"(SE {e['ols_slope_se']:.3f}), intercept {e['ols_intercept']:.4f}/yr ({e['ols_years'][0]}-{e['ols_years'][1]}).\n"]
    hc = sc[sc.fy_end_year == H][["scenario", "domestic_generation_twh", "imported_generation_twh", "total_generation_twh"]]
    L += [f"**Headline accounting, {fy(H)}** (domestic = generated in India; imports = assumed Bhutan imports held at "
          f"{fy(C.BASE_FY_END)} level; total = CEA definition):\n", _md(hc.round(3)), "\n"]
    cols = ["scenario", "fy_end_year", "domestic_generation_twh", "imported_generation_twh", "total_generation_twh",
            "population_m", "urban_pct", "per_capita_domestic_generation_kwh", "non_fossil_share",
            "variable_re_share"] + [f"{k}_twh" for k in C.SOURCES]
    t = sc[sc.fy_end_year.isin([2030, 2035, 2040, H])][cols].copy()
    L += [_md(t.round(3)), "\n\nProvisional flags at the headline year:\n"]
    for _, r in sc[sc.fy_end_year == H].iterrows():
        L.append(f"* {r.scenario}: {r.provisional_flags}")
    L += ["\n\nExternal cross-check (NEP requirement converted to generation-equivalent; requirement is not generation):\n",
          _md(nep.drop(columns=["value_type"]).round(1)), "\n"]

    dm = pd.read_csv(C.OUTPUTS / "demography_sensitivity.csv")
    L += ["## 3b. Population growth and urbanization\n",
          "Official TG (NCP/MoHFW 2020) projections to 2036, extrapolated to 2047 (assumption). The central demographic path "
          "is embedded in the GDP path, so it leaves generation unchanged; variants hold per-capita income fixed:\n",
          _md(dm.drop(columns=["value_type", "variant_label"]).round(3)), "\n"]
    mh = pd.read_csv(C.OUTPUTS / "mix_hydro_vs_potential.csv")
    L += ["Assumed hydro vs indicative CEA-potential energy ceiling (all-India):\n", _md(mh.round(3)), "\n"]
    L += ["## 4. Illustrative regional allocation (generation-conserving; not a physical feasibility proof)\n",
          f"Observed regional generation share {fy(C.BASE_FY_END)}: {am['observed_generation_share_base_year']}.\n",
          f"Solver: {am['n_solves']} solves, all converged = {am['solver_all_success']}; max conservation residual before "
          f"rescale {am['max_conservation_residual_before_rescale_twh']:.2e} TWh; conservation checks passed = "
          f"{bool(cons.passed.all())}.\n"]
    r = rs[rs.fy_end_year == H][["scenario", "region", "generation_twh", "share_of_national", "demand_proxy_share",
                                 "indicative_net_export_twh", "non_fossil_share", "variable_re_share"]]
    L += [_md(r.round(3)), "\n\nCentral scenario, headline year, region x source (TWh):\n"]
    p = al[(al.scenario == "central") & (al.fy_end_year == H)].pivot(index="region", columns="source", values="twh")[C.SOURCES]
    p["total"] = p.sum(axis=1)
    L += [_md(p.reset_index().round(1)), "\n"]
    hy = pd.read_csv(C.OUTPUTS / "hydro_potential_check.csv")
    hy = hy[hy.case.str.startswith(("v1.0", "v1.1"))].drop(columns=["value_type"])
    L += ["Hydro allocation vs indicative CEA-potential ceiling (v1.0 settings vs v1.1 default):\n", _md(hy.round(3)), "\n"]
    sv = pd.read_csv(C.OUTPUTS / "allocation_sensitivity.csv")
    sv = sv[sv.scenario == "central"].pivot(index="case", columns="region", values="indicative_net_export_twh").reset_index()
    L += ["Sensitivity of indicative net transfer (TWh), central scenario:\n", _md(sv.round(1)), "\n"]
    L += ["## 5. Data validation\n",
          f"{len(chk)} checks, {int(chk.passed.sum())} passed, {int((~chk.passed).sum())} failed "
          f"({', '.join(chk.loc[~chk.passed, 'check_id'])} - source-internal inconsistency, documented).\n"]
    (C.REPORTS / "results_summary.md").write_text("\n".join(L))
    print("[report] reports/results_summary.md written")


if __name__ == "__main__":
    main()
